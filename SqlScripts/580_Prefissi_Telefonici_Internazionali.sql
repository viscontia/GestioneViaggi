-- =============================================================================
-- 580 — I prefissi telefonici internazionali diventano una tabella
-- =============================================================================
--
-- Deciso il 2026-09-04, durante i test del sito. Fino a qui il prefisso
-- internazionale non era un dato codificato da nessuna parte:
--
--   * nel GESTIONALE era un campo di TESTO LIBERO — si digitava qualunque cosa;
--   * nel SITO era una tendina di DIECI voci, tutte europee, scritte a mano in
--     Classi_Tabelle_Statiche/pref_tel_internazionali.py.
--
-- Le conseguenze erano gia' nei dati: un cliente con +27 (Sudafrica) o +34
-- (Spagna) arrivava al sito con il campo VUOTO, perche' quei prefissi la tendina
-- non li conosce — e salvando avrebbe perso il dato. E `+39` esiste in DUE
-- varianti, 431 volte e 7: con e senza spazi, perche' nessuno lo normalizzava.
--
-- La lista non e' un'opinione: e' lo standard ITU-E.164, e la sua sede e' il
-- database, dove la raggiungono entrambi i software.
--
-- I NOMI DEI PAESI NON SI RISCRIVONO: stanno gia' in eba_countries (249 paesi,
-- tutti con name_it). Qui c'e' solo la mappa paese → prefisso, verificata contro
-- quella tabella: 249 righe, nessun paese mancante, nessun duplicato.
-- =============================================================================

CREATE TABLE IF NOT EXISTS ana_tel_pref_int (
    pref_int_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Il prefisso come si compone, col +. E' questo che finisce in
    -- ana_clienti.cliente_preftelint, ed e' la ragione per cui non e' un intero.
    pref_int_codice  VARCHAR(6) NOT NULL,
    -- Il paese, come lo conosce eba_countries.
    pref_int_iso2    CHAR(2)    NOT NULL REFERENCES eba_countries(iso_alpha2),
    -- Un paese si puo' disattivare senza perdere lo storico di chi lo usa gia'.
    pref_int_attivo  BOOLEAN    NOT NULL DEFAULT TRUE,
    CONSTRAINT ana_tel_pref_int_uk UNIQUE (pref_int_iso2)
);

COMMENT ON TABLE ana_tel_pref_int IS
'Prefissi telefonici internazionali (ITU-E.164), uno per paese. I nomi dei paesi
stanno in eba_countries e non si duplicano qui. Usata dal gestionale e dal sito.';

-- Piu' paesi condividono lo stesso prefisso (+1 Stati Uniti e Canada, +7 Russia e
-- Kazakistan, +39 Italia e Vaticano): l'unicita' e' sul PAESE, non sul codice.
CREATE INDEX IF NOT EXISTS ana_tel_pref_int_codice_idx ON ana_tel_pref_int (pref_int_codice);


