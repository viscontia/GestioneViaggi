-- ---------------------------------------------------------------------------
-- La lettura, con il nome del paese preso da dove gia' vive.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_ana_tel_pref_int_get_all()
RETURNS TABLE(
    codice      VARCHAR,
    iso2        CHAR,
    paese       VARCHAR,
    descrizione TEXT
)
LANGUAGE sql
STABLE
AS $$
    SELECT p.pref_int_codice, p.pref_int_iso2, c.name_it,
           -- «+39 Italia»: si cerca sia digitando il numero sia il nome del paese,
           -- ed e' la stessa etichetta nei due software.
           (p.pref_int_codice || ' ' || c.name_it)::TEXT
    FROM ana_tel_pref_int p
    JOIN eba_countries c ON c.iso_alpha2 = p.pref_int_iso2
    WHERE p.pref_int_attivo
    -- L'Italia in cima: e' il caso di quasi tutti (431 clienti su 452). Poi in
    -- ordine alfabetico di paese, che e' come le persone li cercano.
    ORDER BY (p.pref_int_iso2 <> 'IT'), c.name_it;
$$;

COMMENT ON FUNCTION fn_ana_tel_pref_int_get_all() IS
'I prefissi telefonici selezionabili, con il nome italiano del paese. Italia in
testa, poi alfabetico. Unica fonte per il gestionale e per il sito di iscrizione.';


